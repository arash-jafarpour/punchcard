func TestAssetForPlatform(t *testing.T) {
	ext := ".tar.gz"
	if runtime.GOOS == "windows" {
		ext = ".zip"
	}
	wanted := "punchcard_" + runtime.GOOS + "_" + runtime.GOARCH + ext

	release := ghRelease{
		TagName: "v0.1.0",
		Assets: []ghAsset{
			{Name: "punchcard_freebsd_riscv64.tar.gz"},
			{Name: wanted},
			{Name: wanted + ".sha256"},
		},
	}
	got, err := release.assetForPlatform()
	if err != nil {
		t.Fatalf("assetForPlatform: %v", err)
	}
	if got.Name != wanted {
		t.Errorf("asset = %q, want %q", got.Name, wanted)
	}
}

