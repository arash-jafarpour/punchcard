func releaseHandler(t *testing.T, release ghRelease) *httptest.Server {
	t.Helper()
	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if r.Header.Get("User-Agent") == "" {
			t.Error("request has no User-Agent")
		}
		if err := json.NewEncoder(w).Encode(release); err != nil {
			t.Errorf("encode: %v", err)
		}
	}))
	t.Cleanup(srv.Close)
	return srv
}

func TestLatestRelease(t *testing.T) {
	want := ghRelease{
		TagName: "v0.2.0",
		Body:    "## Features\n- a thing",
		Assets:  []ghAsset{{Name: "punchcard_linux_amd64.tar.gz"}},
	}
	srv := releaseHandler(t, want)

	c := newClient(Options{RepoSlug: "owner/name", APIBase: srv.URL})
	got, err := c.latestRelease(context.Background())
	if err != nil {
		t.Fatalf("latestRelease: %v", err)
	}
	if got.TagName != want.TagName || got.Body != want.Body {
		t.Errorf("release = %+v, want %+v", got, want)
	}
}

func TestLatestReleaseErrors(t *testing.T) {
	tests := []struct {
		name    string
		status  int
		headers map[string]string
		want    string
	}{
		{
			name:    "rate limit",
			status:  http.StatusForbidden,
			headers: map[string]string{"X-RateLimit-Remaining": "0"},
			want:    "rate limit",
		},
		{
			name:   "no releases",
			status: http.StatusNotFound,
			want:   "no published releases",
		},
		{
			name:   "server error",
			status: http.StatusBadGateway,
			want:   "502",
		},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, _ *http.Request) {
				for key, value := range test.headers {
					w.Header().Set(key, value)
				}
				w.WriteHeader(test.status)
			}))
			defer srv.Close()

			c := newClient(Options{RepoSlug: "owner/name", APIBase: srv.URL})
			_, err := c.latestRelease(context.Background())
			if err == nil || !strings.Contains(err.Error(), test.want) {
				t.Errorf("error = %v, want %q", err, test.want)
			}
		})
	}
}

