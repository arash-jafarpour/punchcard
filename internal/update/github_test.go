func TestChecksumFor(t *testing.T) {
	const digest = "0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef"
	asset := "punchcard_linux_amd64.tar.gz"

	tests := []struct {
		name string
		body string
		want string
	}{
		{
			name: "bare hex",
			body: digest + "\n",
			want: digest,
		},
		{
			// GoReleaser writes no trailing newline.
			name: "bare hex without newline",
			body: digest,
			want: digest,
		},
		{
			name: "name column",
			body: digest + "  " + asset + "\n",
			want: digest,
		},
		{
			name: "other asset first",
			body: strings.Repeat("f", 64) + "  other.tar.gz\n" + digest + "  " + asset + "\n",
			want: digest,
		},
		{
			name: "comment and blank lines",
			body: "# generated by goreleaser\n\n" + digest + "\n",
			want: digest,
		},
		{
			name: "upper case is lowered",
			body: strings.ToUpper(digest) + "\n",
			want: digest,
		},
	}

	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, _ *http.Request) {
				_, _ = w.Write([]byte(test.body))
			}))
			defer srv.Close()

			release := ghRelease{
				TagName: "v0.1.0",
				Assets: []ghAsset{
					{Name: asset + ".sha256", BrowserDownloadURL: srv.URL},
				},
			}
			c := newClient(Options{RepoSlug: "owner/name"})
			got, err := c.checksumFor(context.Background(), &release, asset)
			if err != nil {
				t.Fatalf("checksumFor: %v", err)
			}
			if got != test.want {
				t.Errorf("digest = %q, want %q", got, test.want)
			}
		})
	}
}

func TestChecksumForErrors(t *testing.T) {
	asset := "punchcard_linux_amd64.tar.gz"

	t.Run("no sidecar", func(t *testing.T) {
		release := ghRelease{TagName: "v0.1.0"}
		c := newClient(Options{RepoSlug: "owner/name"})
		_, err := c.checksumFor(context.Background(), &release, asset)
		if err == nil || !strings.Contains(err.Error(), "sidecar") {
			t.Errorf("error = %v, want a sidecar error", err)
		}
	})

	t.Run("bad digest", func(t *testing.T) {
		srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, _ *http.Request) {
			_, _ = w.Write([]byte("not-a-digest\n"))
		}))
		defer srv.Close()

		release := ghRelease{
			TagName: "v0.1.0",
			Assets:  []ghAsset{{Name: asset + ".sha256", BrowserDownloadURL: srv.URL}},
		}
		c := newClient(Options{RepoSlug: "owner/name"})
		_, err := c.checksumFor(context.Background(), &release, asset)
		if err == nil || !strings.Contains(err.Error(), "could not find") {
			t.Errorf("error = %v, want a missing-digest error", err)
		}
	})
}
